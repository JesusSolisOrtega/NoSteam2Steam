"""Wine/Proton registry parser and extractor for Windows registry-based game saves."""

import logging
from pathlib import Path
import re
from typing import Optional

logger = logging.getLogger(__name__)


def normalize_registry_key(key: str) -> tuple[str, str]:
    """
    Normalizes a registry key into (hive, subkey).
    Hive is either 'user' (HKCU) or 'system' (HKLM).
    """
    clean = key.replace("/", "\\").strip("\\")
    if clean.upper().startswith("<WINREGISTRY>"):
        clean = clean[len("<WINREGISTRY>"):].strip("\\")

    hive = "user"
    clean_upper = clean.upper()
    if clean_upper.startswith("HKEY_CURRENT_USER\\") or clean_upper.startswith("HKCU\\"):
        hive = "user"
        clean = re.sub(r"^(HKEY_CURRENT_USER|HKCU)\\", "", clean, flags=re.IGNORECASE)
    elif clean_upper.startswith("HKEY_LOCAL_MACHINE\\") or clean_upper.startswith("HKLM\\"):
        hive = "system"
        clean = re.sub(r"^(HKEY_LOCAL_MACHINE|HKLM)\\", "", clean, flags=re.IGNORECASE)

    return hive, clean


def export_proton_registry_section(pfx_path: Path, registry_key: str) -> Optional[str]:
    """
    Extracts a registry key section from user.reg or system.reg inside a Proton prefix.
    Returns the extracted .reg block content or None if not found.
    """
    hive, subkey = normalize_registry_key(registry_key)
    reg_filename = "user.reg" if hive == "user" else "system.reg"
    reg_file = pfx_path / reg_filename

    if not reg_file.exists():
        logger.debug(f"Registry file not found in prefix: {reg_file}")
        return None

    # In Wine .reg files, sections are formatted like: [Software\\Developer\\Title] timestamp
    escaped_subkey = subkey.replace("\\", "\\\\")
    section_prefix = f"[{escaped_subkey}"

    extracted_lines = []
    in_target_section = False

    try:
        with open(reg_file, "r", encoding="utf-8", errors="replace") as f:
            for line in f:
                stripped = line.strip()
                if stripped.startswith("["):
                    # Check if this header matches the target key or any of its subkeys
                    if stripped.startswith(section_prefix):
                        in_target_section = True
                        extracted_lines.append(line)
                    else:
                        in_target_section = False
                elif in_target_section:
                    extracted_lines.append(line)

        if extracted_lines:
            header = 'WINE REGISTRY Version 2\n;; Auto-generated by NoSteam2Steam\n\n'
            return header + "".join(extracted_lines)
    except Exception as e:
        logger.warning(f"Error reading {reg_file}: {e}")

    return None


def merge_proton_registry_section(pfx_path: Path, reg_content: str, hive: str = "user") -> bool:
    """
    Appends or merges an exported registry block into user.reg or system.reg of a Proton prefix.
    """
    if not reg_content or not reg_content.strip():
        return True

    reg_filename = "user.reg" if hive == "user" else "system.reg"
    reg_file = pfx_path / reg_filename

    if not reg_file.parent.exists():
        logger.warning(f"Prefix directory does not exist: {pfx_path}")
        return False

    try:
        # Strip header if appending
        body_lines = [
            line for line in reg_content.splitlines(keepends=True)
            if not line.startswith("WINE REGISTRY") and not line.startswith(";;")
        ]
        to_append = "".join(body_lines).strip()
        if not to_append:
            return True

        with open(reg_file, "a", encoding="utf-8") as f:
            f.write(f"\n\n;; Restored by NoSteam2Steam\n{to_append}\n")
        logger.info(f"Registry data successfully restored into {reg_file}")
        return True
    except Exception as e:
        logger.error(f"Error writing to registry file {reg_file}: {e}")
        return False

